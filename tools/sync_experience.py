"""Regenerate the Experience section of index.html from the resume PDF.

Usage: python tools/sync_experience.py
Exits nonzero and leaves index.html untouched if anything fails to parse.
"""
import html
import json
import re
import sys
from pathlib import Path

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / "Resume - DS.pdf"
HTML = ROOT / "index.html"
EXTRAS = Path(__file__).resolve().parent / "experience_extras.json"

START = "<!-- EXPERIENCE:START (generated by tools/sync_experience.py from the resume PDF, do not edit by hand) -->"
END = "<!-- EXPERIENCE:END -->"

DATE = r"[A-Z][a-z]{2,8}\.? \d{4}"
HEADER = re.compile(
    rf"^(?P<org>.+?) \| (?P<title>.+?) (?P<start>{DATE}) - (?P<end>Present|{DATE}) \| (?P<loc>.+)$"
)
MONTHS = {m: i for i, m in enumerate(
    ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"], 1)}


def fail(msg):
    print(f"[sync_experience] ERROR: {msg}. index.html was NOT changed.")
    sys.exit(1)


def date_key(s):
    if s == "Present":
        return (9999, 12)
    mon, year = s.split()
    return (int(year), MONTHS[mon[:3].lower()])


def clean(text):
    text = re.sub(r"(?<=\w)-(?=\w)", " ", text)  # site style: no hyphens
    text = re.sub(r"\s+", " ", text).strip()
    return text.rstrip(".")


def section(text, start, end):
    m = re.search(rf"^\s*{start}\s*$(.*?)^\s*{end}\s*$", text, re.S | re.M)
    if not m:
        fail(f"could not find the {start} ... {end} section in the PDF")
    return m.group(1)


def parse_resume():
    if not PDF.exists():
        fail(f"{PDF.name} not found")
    text = "\n".join(p.extract_text(extraction_mode="layout") for p in PdfReader(PDF).pages)

    entries = []
    for raw in section(text, "EXPERIENCE", "SKILLS").splitlines():
        line = re.sub(r"\s+", " ", raw).strip()
        if not line:
            continue
        if line.startswith("●"):
            if not entries:
                fail("found a bullet before any job header")
            entries[-1]["bullets"].append(line[1:].strip())
            continue
        m = HEADER.match(line)
        if m:
            entries.append({**m.groupdict(), "bullets": []})
        elif entries and entries[-1]["bullets"]:
            prev = entries[-1]["bullets"][-1]
            sep = "" if prev.endswith("-") else " "  # word split across lines at a hyphen
            entries[-1]["bullets"][-1] = prev + sep + line
        else:
            fail(f"unrecognised line in EXPERIENCE: {line!r}")

    if not entries:
        fail("no experience entries parsed")
    for e in entries:
        if not e["bullets"]:
            fail(f"entry '{e['org']} | {e['title']}' has no bullets")
        e["key"] = f"{e['org']} | {e['title']}"
        e["bullets"] = [clean(b) for b in e["bullets"]]

    skills = []
    for line in section(text, "SKILLS", "PROJECTS").splitlines():
        line = re.sub(r"\s+", " ", line).strip()
        if ":" in line:
            for term in re.split(r"[,()]", line.split(":", 1)[1]):
                term = term.strip()
                if len(term) > 1:
                    skills.append(term)
    return entries, skills


def merge_keywords(*groups):
    seen, out = set(), []
    for group in groups:
        for k in group:
            if k.lower() not in seen:
                seen.add(k.lower())
                out.append(k)
    return ", ".join(out)


def render(e, nl):
    esc = lambda s: html.escape(s, quote=False)
    lines = [
        f'    <div class="timeline-item" data-keywords="{html.escape(e["keywords"])}">',
        f"      <h3>{esc(e['title'])}</h3>",
        f'      <p class="timeline-meta">{esc(e["org"])} · {esc(e["start"])} to {esc(e["end"])} · {esc(e["loc"])}</p>',
        "      <ul>",
        *[f"        <li>{esc(b)}</li>" for b in e["bullets"]],
        "      </ul>",
        "    </div>",
    ]
    return nl.join(lines)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    entries, skills = parse_resume()
    config = json.loads(EXTRAS.read_text(encoding="utf-8"))
    manual = config.get("keywords", {})

    for e in entries:
        if e["key"] not in manual:
            print(f"[sync_experience] WARNING: no keywords in experience_extras.json for '{e['key']}'")
        found = [s for s in skills
                 if re.search(rf"(?<!\w){re.escape(s)}(?!\w)", " ".join(e["bullets"]), re.I)]
        e["keywords"] = merge_keywords(
            [k.strip() for k in manual.get(e["key"], "").split(",") if k.strip()], found)

    for x in config.get("extras", []):
        entries.append({"title": x["title"], "org": x["org"], "start": x["start"], "end": x["end"],
                        "loc": x["location"], "bullets": x["bullets"], "keywords": x.get("keywords", "")})

    entries.sort(key=lambda e: date_key(e["start"]))           # tiebreak: earlier start first
    entries.sort(key=lambda e: date_key(e["end"]), reverse=True)  # stable: most recent end first

    with open(HTML, encoding="utf-8", newline="") as f:
        page = f.read()
    nl = "\r\n" if "\r\n" in page else "\n"
    i, j = page.find(START), page.find(END)
    if i == -1 or j == -1 or j < i:
        fail("START/END markers not found in index.html")

    block = START + nl + (nl + nl).join(render(e, nl) for e in entries) + nl + "    " + END
    new_page = page[:i] + block + page[j + len(END):]

    for e in entries:
        print(f"[sync_experience] {e['title']} @ {e['org']}: {len(e['bullets'])} bullets")
    if new_page == page:
        print("[sync_experience] Experience already up to date.")
        return
    tmp = HTML.with_suffix(".html.tmp")
    with open(tmp, "w", encoding="utf-8", newline="") as f:
        f.write(new_page)
    tmp.replace(HTML)
    print("[sync_experience] index.html updated.")


if __name__ == "__main__":
    main()
